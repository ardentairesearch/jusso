async fn existing_treasury_operation(
    state: &AppState,
    auth: &AuthContext,
    row: crate::treasury::TreasuryOperationRow,
) -> anyhow::Result<serde_json::Value> {
    let execution = match row.execution_request_id {
        Some(request_id) => services::handle_execution_status(&state.db_pool, auth, request_id)
            .await?
            .map(serde_json::to_value)
            .transpose()?,
        None => None,
    };
    Ok(serde_json::json!({
        "operation_id": row.id,
        "request_id": row.client_request_id,
        "operation": row.operation_kind,
        "status": execution.as_ref().and_then(|value| value.get("status")).cloned().unwrap_or_else(|| serde_json::Value::String(row.status.clone())),
        "execution": execution,
        "result": row.result,
        "error": row.error_message,
        "message": if row.execution_request_id.is_some() {
            "This request was already accepted; returning its current status."
        } else if row.status == "preparing" {
            "This request is already being prepared. Check again shortly with the same request_id."
        } else {
            "The previous attempt failed. Retry with the same request_id."
        }
    }))
}

async fn execute_swap_to_usdc(
    state: &AppState,
    auth: &AuthContext,
    agent_id: &str,
    params: ExecuteSwapParams,
) -> anyhow::Result<serde_json::Value> {
    let policy = require_workflow_action(state, auth, agent_id, "swap:execute").await?;
    let settings = crate::treasury::get_settings(
        &state.db_pool,
        auth.organization_id,
        auth.agent_id.context("agent access token is not bound")?,
    )
    .await?
    .context("the owner has not configured autonomous treasury rules")?;
    if !settings.swaps_enabled {
        anyhow::bail!("the owner has not enabled autonomous conversions for this agent");
    }
    let (_, wallet) = managed_treasury_wallet(state, auth, agent_id).await?;
    let token = crate::circle::resolve_swap_token(state.config.arc_network, &params.token)?;
    let (symbol, decimals) = token_metadata(state, token).await?;
    let amount_raw = crate::circle::parse_token_amount(&params.amount, decimals)?;
    let impact = crate::policy::ExecutionPolicyImpact::token_spend(token, amount_raw);
    crate::auth::enforce_policy_impact(&policy, &impact).with_context(|| {
        format!(
            "the owner has not authorized this {symbol} conversion amount; update the agent policy first"
        )
    })?;
    let reservation = crate::treasury::reserve_operation(
        &state.db_pool,
        auth.organization_id,
        auth.agent_id.unwrap(),
        "swap_to_usdc",
        params.request_id.trim(),
        &params,
    )
    .await?;
    if !reservation.acquired {
        return existing_treasury_operation(state, auth, reservation.row).await;
    }
    let operation_id = reservation.row.id;
    let result: anyhow::Result<serde_json::Value> = async {
        let chain = crate::types::Chain::from_str_loose(state.config.arc_network.name())
            .context("configured Arc network is invalid")?;
        let provider = state.engine.provider_for_chain(&chain)?;
        let balance = services::fetch_erc20_balance_of(provider.as_ref(), token, wallet).await?;
        if balance < amount_raw {
            anyhow::bail!(
                "insufficient {symbol} balance: available {}, requested {}",
                crate::circle::format_token_amount(balance, decimals),
                params.amount.trim()
            );
        }
        let circle = state
            .circle
            .as_ref()
            .context("Circle services are not enabled")?;
        let quote = circle
            .quote_swap_to_usdc(
                state.config.arc_network,
                wallet,
                token,
                amount_raw,
                settings.max_slippage_bps as u16,
            )
            .await?;
        if U256::from_dec_str(&quote.estimated_usdc_raw)? > settings.max_swap_raw()? {
            anyhow::bail!("this conversion is above the owner-approved per-conversion limit");
        }
        let prepared = circle
            .prepare_swap_to_usdc(
                state.config.arc_network,
                wallet,
                token,
                amount_raw,
                settings.max_slippage_bps as u16,
                &quote,
            )
            .await?;
        let request = crate::types::ExecutionRequest {
            agent_id: agent_id.to_string(),
            chain: state.config.arc_network.name().into(),
            target_contract: String::new(),
            calldata: String::new(),
            value: "0".into(),
            strategy_id: Some("circle-swap-to-usdc".into()),
            batch_calls: Some(prepared.calls),
            callback_url: None,
            policy_impact: impact,
        };
        let mut redis = state.redis_conn.clone();
        let execution = services::handle_execute_idempotent(
            &state.engine,
            &state.db_pool,
            &mut redis,
            &state.wallet_registry,
            auth,
            &request,
            &format!("treasury-{operation_id}"),
        )
        .await?;
        let summary = serde_json::json!({
            "conversion": friendly_swap_quote(&quote, &symbol, decimals),
            "execution": execution
        });
        crate::treasury::complete_operation(
            &state.db_pool,
            operation_id,
            &prepared.provider_execution_id,
            execution.request_id,
            &execution.status.to_string(),
            &summary,
        )
        .await?;
        Ok(serde_json::json!({
            "operation_id": operation_id,
            "request_id": params.request_id,
            "status": execution.status,
            "conversion": friendly_swap_quote(&quote, &symbol, decimals),
            "execution": execution
        }))
    }
    .await;
    if let Err(error) = &result {
        crate::treasury::fail_operation(&state.db_pool, operation_id, error).await;
    }
    result
}

async fn execute_earn_action(
    state: &AppState,
    auth: &AuthContext,
    agent_id: &str,
    params: EarnActionParams,
    withdrawal: bool,
) -> anyhow::Result<serde_json::Value> {
    let action = if withdrawal {
        "earn:withdraw"
    } else {
        "earn:deposit"
    };
    let policy = require_workflow_action(state, auth, agent_id, action).await?;
    let settings = crate::treasury::get_settings(
        &state.db_pool,
        auth.organization_id,
        auth.agent_id.context("agent access token is not bound")?,
    )
    .await?
    .context("the owner has not configured autonomous treasury rules")?;
    if !withdrawal && !settings.earn_enabled {
        anyhow::bail!("the owner has not enabled autonomous earnings for this agent");
    }
    let vault = parse_nonzero_address(&params.vault_address, "vault_address")?;
    if !withdrawal && !settings.allows_vault(vault) {
        anyhow::bail!("this earn opportunity is not in the owner's approved list");
    }
    let amount_raw = crate::circle::parse_token_amount(&params.amount, 6)?;
    let impact = if withdrawal {
        crate::policy::ExecutionPolicyImpact::default()
    } else {
        crate::policy::ExecutionPolicyImpact::token_spend(crate::arc::ARC_USDC_ADDRESS, amount_raw)
    };
    crate::auth::enforce_policy_impact(&policy, &impact)
        .context("the owner has not authorized this Earn amount")?;
    let (_, wallet) = managed_treasury_wallet(state, auth, agent_id).await?;
    let kind = if withdrawal {
        "earn_withdraw"
    } else {
        "earn_deposit"
    };
    let reservation = crate::treasury::reserve_operation(
        &state.db_pool,
        auth.organization_id,
        auth.agent_id.unwrap(),
        kind,
        params.request_id.trim(),
        &params,
    )
    .await?;
    if !reservation.acquired {
        return existing_treasury_operation(state, auth, reservation.row).await;
    }
    let operation_id = reservation.row.id;
    let result: anyhow::Result<serde_json::Value> = async {
        let circle = state
            .circle
            .as_ref()
            .context("Circle services are not enabled")?;
        let chain = crate::types::Chain::from_str_loose(state.config.arc_network.name())
            .context("configured Arc network is invalid")?;
        let provider = state.engine.provider_for_chain(&chain)?;
        let opportunity_name = if withdrawal {
            format!("USDC Earn position at {vault:?}")
        } else {
            approved_vault_snapshots(
                circle,
                state.config.arc_network,
                &[format!("{vault:?}")],
            )
            .await?
            .into_iter()
            .next()
            .context("earn opportunity is unavailable")?
            .name
        };
        if withdrawal {
            let available =
                services::fetch_erc4626_max_withdraw(provider.as_ref(), vault, wallet).await?;
            if amount_raw > available {
                anyhow::bail!(
                    "withdrawal exceeds the currently available position of {} USDC",
                    crate::circle::format_token_amount(available, 6)
                );
            }
        } else {
            let mut total_allocation = U256::zero();
            for approved in &settings.allowed_earn_vaults {
                let approved_vault = parse_nonzero_address(approved, "approved earn vault")?;
                let allocation = services::fetch_erc4626_asset_balance(
                    provider.as_ref(),
                    approved_vault,
                    wallet,
                )
                .await?;
                total_allocation = total_allocation
                    .checked_add(allocation)
                    .context("total Earn allocation overflow")?;
            }
            if total_allocation
                .checked_add(amount_raw)
                .context("earn allocation overflow")?
                > settings.max_earn_raw()?
            {
                anyhow::bail!("this deposit would exceed the owner-approved Earn allocation cap");
            }
            let balance = services::fetch_erc20_balance_of(
                provider.as_ref(),
                crate::arc::ARC_USDC_ADDRESS,
                wallet,
            )
            .await?;
            let fee_buffer = crate::execution_engine::pricing::usd_to_token_raw_amount(
                policy.max_execution_fee_usd.unwrap_or_default(),
                6,
            )?;
            let required = amount_raw
                .checked_add(settings.minimum_reserve_raw()?)
                .and_then(|amount| amount.checked_add(fee_buffer))
                .context("required USDC amount overflow")?;
            if balance < required {
                anyhow::bail!(
                    "this deposit would reduce available USDC below the owner's reserve after the maximum execution fee"
                );
            }
        }
        let quote = circle
            .earn_quote(
                state.config.arc_network,
                wallet,
                vault,
                params.amount.trim(),
                withdrawal,
            )
            .await?;
        let prepared = circle
            .prepare_earn(
                state.config.arc_network,
                wallet,
                vault,
                params.amount.trim(),
                withdrawal,
            )
            .await?;
        let request = crate::types::ExecutionRequest {
            agent_id: agent_id.to_string(),
            chain: state.config.arc_network.name().into(),
            target_contract: String::new(),
            calldata: String::new(),
            value: "0".into(),
            strategy_id: Some(if withdrawal {
                "circle-earn-withdraw".into()
            } else {
                "circle-earn-deposit".into()
            }),
            batch_calls: Some(prepared.calls),
            callback_url: None,
            policy_impact: impact,
        };
        let mut redis = state.redis_conn.clone();
        let execution = services::handle_execute_idempotent(
            &state.engine,
            &state.db_pool,
            &mut redis,
            &state.wallet_registry,
            auth,
            &request,
            &format!("treasury-{operation_id}"),
        )
        .await?;
        let summary = serde_json::json!({
            "action": if withdrawal { "withdraw" } else { "deposit" },
            "opportunity": opportunity_name,
            "amount_usdc": params.amount.trim(),
            "quote": quote,
            "execution": execution
        });
        crate::treasury::complete_operation(
            &state.db_pool,
            operation_id,
            &prepared.provider_execution_id,
            execution.request_id,
            &execution.status.to_string(),
            &summary,
        )
        .await?;
        Ok(serde_json::json!({
            "operation_id": operation_id,
            "request_id": params.request_id,
            "status": execution.status,
            "action": if withdrawal { "withdraw" } else { "deposit" },
            "opportunity": opportunity_name,
            "amount_usdc": params.amount.trim(),
            "quote": quote,
            "execution": execution
        }))
    }
    .await;
    if let Err(error) = &result {
        crate::treasury::fail_operation(&state.db_pool, operation_id, error).await;
    }
    result
}

fn parse_nonzero_address(value: &str, name: &str) -> anyhow::Result<Address> {
    let address: Address = value
        .trim()
        .parse()
        .with_context(|| format!("{name} must be an EVM address"))?;
    if address == Address::zero() {
        anyhow::bail!("{name} cannot be the zero address");
    }
    Ok(address)
}

