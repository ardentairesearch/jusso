#[derive(Clone)]
pub struct AgentMcp {
    state: AppState,
    auth: AuthService,
    tool_router: ToolRouter<Self>,
}

impl AgentMcp {
    fn new(state: AppState, auth: AuthService) -> Self {
        let mut tool_router = Self::runtime_tool_router();
        tool_router.merge(Self::management_tool_router());
        Self {
            state,
            auth,
            tool_router,
        }
    }

    async fn authorize(
        &self,
        context: &RequestContext<RoleServer>,
        chain: Option<&str>,
        scope: &'static str,
        resource: &'static str,
    ) -> Result<(AuthContext, String), ErrorData> {
        let auth = request_auth(context)?;
        let authorized = self
            .auth
            .authorize_mcp_action(&auth, chain, scope, resource)
            .await
            .map_err(tool_error)?;
        let agent_id = authorized
            .agent_external_id
            .clone()
            .ok_or_else(|| tool_error("agent MCP access token is not bound to an agent"))?;
        Ok((authorized, agent_id))
    }
}

