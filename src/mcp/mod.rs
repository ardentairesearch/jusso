    #[tool(
        description = "Create a one-time owner passkey review for simple autonomous conversion and earnings rules. After approval, actions inside these limits run without repeated browser prompts."
    )]
    async fn request_configure_treasury_approval(
        &self,
        Parameters(params): Parameters<ConfigureTreasuryParams>,
        context: RequestContext<RoleServer>,
    ) -> Result<McpJson<serde_json::Value>, ErrorData> {
        let auth = request_auth(&context)?;
        require_scope(&auth, "workflow:manage")?;
        let agent_uuid = auth
            .agent_id
            .ok_or_else(|| tool_error("select an agent before configuring its treasury"))?;
        let existing =
            crate::treasury::get_settings(&self.state.db_pool, auth.organization_id, agent_uuid)
                .await
                .map_err(tool_error)?;
        let max_swap = if params.enable_conversions {
            crate::circle::parse_token_amount(
                params.maximum_conversion_usdc.as_deref().unwrap_or("500"),
                6,
            )
            .map_err(tool_error)?
        } else {
            U256::zero()
        };
        let reserve = if params.enable_earnings {
            crate::circle::parse_token_amount(
                params.minimum_available_usdc.as_deref().unwrap_or("50"),
                6,
            )
            .map_err(tool_error)?
        } else {
            U256::zero()
        };
        let max_earn = if params.enable_earnings {
            crate::circle::parse_token_amount(
                params.maximum_earn_usdc.as_deref().unwrap_or("500"),
                6,
            )
            .map_err(tool_error)?
        } else {
            U256::zero()
        };
        let tolerance = params.maximum_price_movement_percent.unwrap_or(1.0);
        if !tolerance.is_finite() || !(0.1..=5.0).contains(&tolerance) {
            return Err(tool_error(
                "maximum_price_movement_percent must be between 0.1 and 5",
            ));
        }
        let slippage_bps = (tolerance * 100.0).round() as i32;
        if params.enable_conversions || params.enable_earnings {
            let _ = circle_client(&self.state)?;
            if crate::byow::active_connection_for_agent(
                &self.state.db_pool,
                auth.organization_id,
                agent_uuid,
            )
            .await
            .map_err(tool_error)?
            .is_some()
            {
                return Err(tool_error(
                    "autonomous conversions and earnings currently require the Jusso-managed wallet; disconnect the Circle Agent Wallet before enabling them",
                ));
            }
        }
        let vaults = if params.enable_earnings {
            if params.earn_vault_addresses.is_empty() {
                return Err(tool_error(
                    "choose at least one opportunity from list_earn_opportunities",
                ));
            }
            approved_vault_snapshots(
                circle_client(&self.state)?,
                self.state.config.arc_network,
                &params.earn_vault_addresses,
            )
            .await
            .map_err(tool_error)?
        } else {
            Vec::new()
        };
        let settings = crate::treasury::TreasurySettingsInput {
            agent_id: agent_uuid,
            expected_version: existing.map(|settings| settings.version),
            swaps_enabled: params.enable_conversions,
            earn_enabled: params.enable_earnings,
            max_swap_usdc_raw: if params.enable_conversions {
                max_swap.to_string()
            } else {
                "0".into()
            },
            max_slippage_bps: slippage_bps,
            minimum_liquid_usdc_raw: reserve.to_string(),
            max_earn_allocation_usdc_raw: max_earn.to_string(),
            earn_vaults: vaults,
        };
        self.request_owner_approval(
            &auth,
            db::OwnerApprovalAction::ConfigureTreasury { settings },
        )
        .await
    }

