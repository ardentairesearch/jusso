async fn token_metadata(state: &AppState, token: Address) -> anyhow::Result<(String, u8)> {
    let chain = crate::types::Chain::from_str_loose(state.config.arc_network.name())
        .context("configured Arc network is invalid")?;
    let provider = state.engine.provider_for_chain(&chain)?;
    if provider.get_code(token).await?.is_empty() {
        anyhow::bail!("the selected token has no contract on the configured Arc network");
    }
    let symbol = services::read_erc20_symbol(provider.as_ref(), token)
        .await
        .context("token symbol could not be read")?;
    let decimals = services::read_erc20_decimals(provider.as_ref(), token)
        .await
        .context("token decimals could not be read")?;
    if decimals > 36 {
        anyhow::bail!("the selected token uses unsupported decimal precision");
    }
    Ok((symbol, decimals))
}

async fn require_workflow_action(
    state: &AppState,
    auth: &AuthContext,
    agent_id: &str,
    action: &str,
) -> anyhow::Result<crate::db::models::AuthorizationPolicyRow> {
    let (_, policy) = db::authorize_execution_agent(&state.db_pool, auth, agent_id).await?;
    if !policy.allowed_actions.as_ref().is_some_and(|actions| {
        actions
            .iter()
            .any(|allowed| allowed == "*" || allowed == action)
    }) {
        anyhow::bail!("the agent's authorization policy does not allow {action}");
    }
    Ok(policy)
}

