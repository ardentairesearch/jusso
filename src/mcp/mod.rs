    #[tool(
        description = "Preview converting a supported Arc asset into USDC. Returns the expected and minimum USDC without moving funds or requiring approval."
    )]
    async fn quote_conversion_to_usdc(
        &self,
        Parameters(params): Parameters<SwapAmountParams>,
        context: RequestContext<RoleServer>,
    ) -> Result<McpJson<serde_json::Value>, ErrorData> {
        let (auth, agent_id) = self
            .authorize(
                &context,
                Some(self.state.config.arc_network.name()),
                "workflow:read",
                "swap:quote",
            )
            .await?;
        let circle = circle_client(&self.state)?;
        let (_, wallet) = managed_treasury_wallet(&self.state, &auth, &agent_id)
            .await
            .map_err(tool_error)?;
        let token = crate::circle::resolve_swap_token(self.state.config.arc_network, &params.token)
            .map_err(tool_error)?;
        let (symbol, decimals) = token_metadata(&self.state, token)
            .await
            .map_err(tool_error)?;
        let amount_raw =
            crate::circle::parse_token_amount(&params.amount, decimals).map_err(tool_error)?;
        let settings = crate::treasury::get_settings(
            &self.state.db_pool,
            auth.organization_id,
            auth.agent_id.unwrap(),
        )
        .await
        .map_err(tool_error)?;
        let slippage = settings
            .as_ref()
            .map_or(100, |settings| settings.max_slippage_bps as u16);
        let quote = circle
            .quote_swap_to_usdc(
                self.state.config.arc_network,
                wallet,
                token,
                amount_raw,
                slippage,
            )
            .await
            .map_err(tool_error)?;
        json_output(friendly_swap_quote(&quote, &symbol, decimals))
    }

